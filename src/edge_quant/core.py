"""Core utilities for a lightweight Edge-AI quantization benchmark.

This implementation intentionally avoids TensorFlow/PyTorch so it can run on
Windows, Raspberry Pi, Jetson, or a basic CI runner. It models the same
engineering workflow as a real TFLite project:

1. Train a small model.
2. Export FP32, float16/dynamic, and int8 variants.
3. Benchmark latency/FPS/model-size/RAM.
4. Generate CSV, plot, and demo artifact.

The model is a compact linear image classifier trained on synthetic
image-like features. It is not meant to be state-of-the-art; it is meant to be
fully reproducible and easy to deploy on constrained machines.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
import csv
import os
import time
from datetime import datetime

import numpy as np

try:
    import psutil
except Exception:  # pragma: no cover
    psutil = None


@dataclass
class Dataset:
    x_train: np.ndarray
    y_train: np.ndarray
    x_test: np.ndarray
    y_test: np.ndarray


@dataclass
class TrainedModel:
    weights: np.ndarray
    bias: np.ndarray
    accuracy: float


def softmax(logits: np.ndarray) -> np.ndarray:
    logits = logits - np.max(logits, axis=1, keepdims=True)
    exp = np.exp(logits)
    return exp / np.sum(exp, axis=1, keepdims=True)


def one_hot(labels: np.ndarray, n_classes: int) -> np.ndarray:
    out = np.zeros((labels.shape[0], n_classes), dtype=np.float32)
    out[np.arange(labels.shape[0]), labels] = 1.0
    return out


def make_synthetic_dataset(
    seed: int,
    n_train: int,
    n_test: int,
    n_features: int,
    n_classes: int,
) -> Dataset:
    """Create a reproducible synthetic dataset.

    Each class has a prototype vector. Samples are generated by adding noise to
    the prototype. This behaves similarly to a tiny feature-extraction problem
    from images, but it needs no external dataset download.
    """
    rng = np.random.default_rng(seed)
    prototypes = rng.normal(0.0, 1.0, size=(n_classes, n_features)).astype(np.float32)

    def sample(n: int):
        labels = rng.integers(0, n_classes, size=n)
        x = prototypes[labels] + rng.normal(0.0, 0.65, size=(n, n_features)).astype(np.float32)
        x = (x - x.mean(axis=1, keepdims=True)) / (x.std(axis=1, keepdims=True) + 1e-6)
        return x.astype(np.float32), labels.astype(np.int64)

    x_train, y_train = sample(n_train)
    x_test, y_test = sample(n_test)
    return Dataset(x_train=x_train, y_train=y_train, x_test=x_test, y_test=y_test)


def train_linear_classifier(
    dataset: Dataset,
    n_classes: int,
    epochs: int,
    learning_rate: float,
    seed: int,
) -> TrainedModel:
    """Train a compact linear classifier using batch gradient descent."""
    rng = np.random.default_rng(seed)
    n_features = dataset.x_train.shape[1]
    weights = rng.normal(0.0, 0.02, size=(n_features, n_classes)).astype(np.float32)
    bias = np.zeros((n_classes,), dtype=np.float32)
    y_onehot = one_hot(dataset.y_train, n_classes)

    for _ in range(epochs):
        logits = dataset.x_train @ weights + bias
        probs = softmax(logits)
        error = (probs - y_onehot) / dataset.x_train.shape[0]
        grad_w = dataset.x_train.T @ error
        grad_b = error.sum(axis=0)
        weights -= learning_rate * grad_w.astype(np.float32)
        bias -= learning_rate * grad_b.astype(np.float32)

    preds = predict_fp32(dataset.x_test, weights, bias)
    accuracy = float(np.mean(preds == dataset.y_test))
    return TrainedModel(weights=weights, bias=bias, accuracy=accuracy)


def predict_fp32(x: np.ndarray, weights: np.ndarray, bias: np.ndarray) -> np.ndarray:
    return np.argmax(x @ weights + bias, axis=1)


def symmetric_int8_quantize(array: np.ndarray) -> tuple[np.ndarray, float]:
    max_abs = float(np.max(np.abs(array)))
    scale = max_abs / 127.0 if max_abs > 0 else 1.0
    q = np.clip(np.round(array / scale), -128, 127).astype(np.int8)
    return q, scale


def export_models(model: TrainedModel, output_dir: Path, model_name: str) -> list[Path]:
    """Export FP32, float16/dynamic, and int8 model files as .npz."""
    output_dir.mkdir(parents=True, exist_ok=True)
    paths = []

    fp32_path = output_dir / f"{model_name}_fp32.npz"
    np.savez(fp32_path, quant_type="fp32", weights=model.weights.astype(np.float32), bias=model.bias.astype(np.float32))
    paths.append(fp32_path)

    dynamic_path = output_dir / f"{model_name}_dynamic_float16.npz"
    np.savez(dynamic_path, quant_type="dynamic_float16", weights=model.weights.astype(np.float16), bias=model.bias.astype(np.float16))
    paths.append(dynamic_path)

    w_q, w_scale = symmetric_int8_quantize(model.weights)
    b_q, b_scale = symmetric_int8_quantize(model.bias)
    int8_path = output_dir / f"{model_name}_int8.npz"
    np.savez(
        int8_path,
        quant_type="int8",
        weights=w_q,
        bias=b_q,
        weight_scale=np.float32(w_scale),
        bias_scale=np.float32(b_scale),
    )
    paths.append(int8_path)

    return paths


def load_model(path: Path) -> dict:
    data = np.load(path, allow_pickle=False)
    return {k: data[k] for k in data.files}


def infer(model_dict: dict, x: np.ndarray) -> np.ndarray:
    quant_type = str(model_dict["quant_type"])
    if quant_type == "fp32":
        weights = model_dict["weights"].astype(np.float32)
        bias = model_dict["bias"].astype(np.float32)
    elif quant_type == "dynamic_float16":
        # Simulates dynamic range quantization: compressed weights, float compute.
        weights = model_dict["weights"].astype(np.float32)
        bias = model_dict["bias"].astype(np.float32)
    elif quant_type == "int8":
        # Simple dequantized matmul path. On real devices this would be mapped to
        # int8 kernels by TFLite/TensorRT.
        weights = model_dict["weights"].astype(np.float32) * float(model_dict["weight_scale"])
        bias = model_dict["bias"].astype(np.float32) * float(model_dict["bias_scale"])
    else:
        raise ValueError(f"Unsupported quant_type: {quant_type}")
    return np.argmax(x @ weights + bias, axis=1)


def benchmark_model(
    model_path: Path,
    x_sample: np.ndarray,
    y_sample: np.ndarray,
    iterations: int,
    warmup_runs: int,
    device: str,
) -> dict:
    model = load_model(model_path)
    batch = x_sample[:1].astype(np.float32)

    for _ in range(warmup_runs):
        infer(model, batch)

    process = psutil.Process(os.getpid()) if psutil is not None else None
    mem_before = process.memory_info().rss if process is not None else 0

    latencies = []
    t_start = time.perf_counter()
    for _ in range(iterations):
        t0 = time.perf_counter()
        infer(model, batch)
        latencies.append((time.perf_counter() - t0) * 1000.0)
    total_time = time.perf_counter() - t_start

    mem_after = process.memory_info().rss if process is not None else mem_before
    ram_delta_mb = max(0, mem_after - mem_before) / (1024 ** 2)

    preds = infer(model, x_sample.astype(np.float32))
    accuracy = float(np.mean(preds == y_sample))

    quant_type = str(model["quant_type"])
    return {
        "model_name": model_path.stem,
        "quant_type": quant_type,
        "file_path": str(model_path),
        "size_mb": round(model_path.stat().st_size / (1024 ** 2), 6),
        "latency_p50_ms": round(float(np.percentile(latencies, 50)), 6),
        "latency_p95_ms": round(float(np.percentile(latencies, 95)), 6),
        "throughput_fps": round(float(iterations / total_time), 3),
        "ram_usage_mb": round(float(ram_delta_mb), 6),
        "accuracy": round(accuracy, 4),
        "device": device,
        "date": datetime.now().strftime("%Y-%m-%d"),
        "notes": "numpy edge baseline; replace with TFLite/TensorRT for hardware kernels",
    }


def write_benchmark_csv(results: list[dict], csv_path: Path) -> None:
    csv_path.parent.mkdir(parents=True, exist_ok=True)
    columns = [
        "model_name",
        "quant_type",
        "file_path",
        "size_mb",
        "latency_p50_ms",
        "latency_p95_ms",
        "throughput_fps",
        "ram_usage_mb",
        "accuracy",
        "device",
        "date",
        "notes",
    ]
    with csv_path.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=columns)
        writer.writeheader()
        writer.writerows(results)
